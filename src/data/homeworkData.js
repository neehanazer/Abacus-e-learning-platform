import { generateQuestionForCategory, PRACTICE_CATEGORIES, } from "./practiceData";
// Generate question set for a specific practice category
export function generateQuestionsForHomework(category, count = 10) {
    const questions = [];
    for (let i = 0; i < count; i++) {
        questions.push(generateQuestionForCategory(category, i + 1));
    }
    return questions;
}
